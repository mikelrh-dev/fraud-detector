code([
"# =============================================================================\n",
"# CELDA 5: FEATURE ENGINEERING - De PaySim a nuestro FeatureEngine\n",
"# =============================================================================\n",
"#\n",
"# Este es el corazon del notebook. Tenemos que transformar las columnas\n",
"# de PaySim a las 10 features que espera nuestro FeatureEngine.\n",
"#\n",
"# Nuestro FeatureEngine original espera:\n",
"#   [amount, amount_vs_user_avg, amount_vs_user_std, tx_count_5min,\n",
"#    tx_count_1h, hour_of_day, is_weekend, merchant_risk_level,\n",
"#    is_crypto, amount_round_number]\n",
"#\n",
"# PaySim no tiene user_id real, ni merchant_name, ni timestamp.\n",
"# Mapeamos lo que podemos y el resto lo dejamos en 0.\n",
"#\n",
"# MAPEO:\n",
"#   PaySim amount        -> amount (directo)\n",
"#   PaySim type          -> merchant_category (LabelEncoder)\n",
"#   amount / oldbalance  -> amount_vs_user_avg (aproximacion)\n",
"#   PaySim step % 24     -> hour_of_day\n",
"#   type=TRANSFER        -> is_crypto = 1 (es la analogia mas cercana)\n",
"#   type=CASH_OUT/TRANSFER -> merchant_risk_level = 1\n",
"#   amount % 100 == 0    -> amount_round_number\n",
"#   (resto)              -> 0\n",
"\n",
"def engineer_features(df: pd.DataFrame) -> pd.DataFrame:\n",
"    \"\"\"Transforma PaySim raw a nuestras 10 features.\n",
"    \n",
"    Cada fila de output es un vector de 10 dimensiones que nuestro\n",
"    MLModelService.predict() va a recibir en produccion.\n",
"    \"\"\"\n",
"    features = pd.DataFrame()\n",
"\n",
"    # 1. AMOUNT: monto bruto\n",
"    # Directo de PaySim, igual que en produccion\n",
"    features[\"amount\"] = df[\"amount\"].astype(float)\n",
"\n",
"    # 2. AMOUNT_VS_USER_AVG: que tan desviado esta del promedio del usuario\n",
"    # PaySim no tiene historial de usuario real. Usamos el balance previo\n",
"    # como proxy: si oldbalanceOrg es 0, no podemos calcular el ratio.\n",
"    # oldbalanceOrg / (amount + 1) nos da una idea de la proporcion.\n",
"    #\n",
"    # En produccion, esto se calcula con el historial real del usuario.\n",
"    old = df[\"oldbalanceOrg\"].astype(float)\n",
"    amt = df[\"amount\"].astype(float)\n",
"    features[\"amount_vs_user_avg\"] = np.where(\n",
"        old > 0,\n",
"        (amt - old) / (old + 1),  # desviacion respecto al saldo previo\n",
"        0.0\n",
"    )\n",
"\n",
"    # 3. AMOUNT_VS_USER_STD: desviacion estandar\n",
"    # Sin historial real, usamos dispersion de todo el dataset\n",
"    # como proxy. No es ideal, pero es un punto de partida.\n",
"    global_std = amt.std()\n",
"    features[\"amount_vs_user_std\"] = np.where(\n",
"        global_std > 0,\n",
"        (amt - amt.mean()) / global_std,\n",
"        0.0\n",
"    )\n",
"\n",
"    # 4 y 5. TX_COUNT: velocidad de transacciones\n",
"    # PaySim no tiene marcas de tiempo reales, solo \"step\" (hora simulada).\n",
"    # Agrupamos por nameOrig y step para estimar velocidad.\n",
"    # Esto es una aproximacion burda pero mejor que 0.\n",
"    velocity = df.groupby([\"nameOrig\", \"step\"]).size().reset_index(name=\"count\")\n",
"    df_with_vel = df.merge(velocity, on=[\"nameOrig\", \"step\"], how=\"left\")\n",
"    features[\"tx_count_last_5min\"] = df_with_vel[\"count\"].fillna(0).astype(float)\n",
"    features[\"tx_count_last_1h\"] = df_with_vel[\"count\"].fillna(0).astype(float)\n",
"\n",
"    # 6. HOUR_OF_DAY: hora del dia\n",
"    # PaySim no tiene timestamp. Usamos step % 24 (cada step = 1 hora).\n",
"    features[\"hour_of_day\"] = (df[\"step\"] % 24).astype(float)\n",
"\n",
"    # 7. IS_WEEKEND: fin de semana\n",
"    # No tenemos dia de la semana real. Dejamos en 0.\n",
"    # En produccion, esto se calcula del timestamp real.\n",
"    features[\"is_weekend\"] = 0.0\n",
"\n",
"    # 8. MERCHANT_RISK_LEVEL: nivel de riesgo del comercio\n",
"    # En PaySim, TRANSFER y CASH_OUT son las operaciones de riesgo\n",
"    # (donde ocurren todos los fraudes). PAYMENT, DEBIT, CASH_IN son seguras.\n",
"    # Mapeamos: TRANSFER/CASH_OUT = riesgo, el resto = seguro.\n",
"    features[\"merchant_risk_level\"] = df[\"type\"].isin([\"TRANSFER\", \"CASH_OUT\"]).astype(float)\n",
"\n",
"    # 9. IS_CRYPTO: es criptomoneda?\n",
"    # PaySim no tiene cripto, pero TRANSFER es la operacion mas cercana\n",
"    # (cambio de dueno sin contraparte comercial registrada).\n",
"    features[\"is_crypto\"] = (df[\"type\"] == \"TRANSFER\").astype(float)\n",
"\n",
"    # 10. AMOUNT_ROUND_NUMBER: monto redondeado\n",
"    # Los montos fraudulentos suelen ser redondos o muy especificos.\n",
"    # Detectar montos multiplo de 1000 es un indicador clasico.\n",
"    features[\"amount_round_number\"] = (\n",
"        (amt > 0) & ((amt % 1000) == 0)\n",
"    ).astype(float)\n",
"\n",
"    return features\n",
"\n",
"\n",
"X = engineer_features(df)\n",
"y = df[\"isFraud\"].values\n",
"\n",
"print(f\"Features generadas: {X.shape[1]}\")\n",
"print(f\"Filas: {X.shape[0]:,}\")\n",
"print(f\"Columnas: {list(X.columns)}\")\n",
"X.head()\n",
])

