code([
"# =============================================================================\n",
"# CELDA 10: AJUSTE DEL UMBRAL DE DECISION\n",
"# =============================================================================\n",
"#\n",
"# XGBoost devuelve una probabilidad (0 a 1). Por defecto, clasifica como\n",
"# fraude si proba > 0.5. Pero en deteccion de fraude, 0.5 rara vez es optimo.\n",
"#\n",
"# Podemos ajustar el UMBRAL para priorizar:\n",
"#   - Umbral BAJO (ej: 0.3): detectamos MAS fraudes (mejor recall)\n",
"#     pero generamos MAS falsas alarmas (peor precision)\n",
"#   - Umbral ALTO (ej: 0.8): detectamos MENOS fraudes (peor recall)\n",
"#     pero las alertas son MAS confiables (mejor precision)\n",
"#\n",
"# Donde poner el umbral depende del negocio:\n",
"#   - Si cada fraude cuesta $10,000 -> umbral BAJO (queremos detectar todo)\n",
"#   - Si cada alerta la revisa un humano -> umbral MEDIO\n",
"#   - Si el sistema bloquea automaticamente -> umbral ALTO\n",
"\n",
"from sklearn.metrics import precision_recall_curve\n",
"\n",
"precisions, recalls, thresholds = precision_recall_curve(y_test, y_proba)\n",
"\n",
"print(\"PRECISION Y RECALL POR UMBRAL:\")\n",
"print(f\"{'Umbral':>8} {'Precision':>12} {'Recall':>10} {'F1':>8}\")\n",
"print(\"-\" * 42)\n",
"\n",
"best_f1 = 0\n",
"best_threshold = 0.5\n",
"for i in range(0, len(thresholds), max(1, len(thresholds) // 20)):\n",
"    t = thresholds[i]\n",
"    p = precisions[i]\n",
"    r = recalls[i]\n",
"    f1 = 2 * p * r / (p + r) if (p + r) > 0 else 0\n",
"    if f1 > best_f1:\n",
"        best_f1 = f1\n",
"        best_threshold = t\n",
"    print(f\"{t:>8.3f} {p:>12.4f} {r:>10.4f} {f1:>8.4f}\")\n",
"\n",
"print(f\"\\nMejor umbral por F1: {best_threshold:.3f} (F1={best_f1:.4f})\")\n",
"print(f\"Umbral default (0.5): F1={f1_score(y_test, y_pred):.4f}\")\n",
"\n",
"# En produccion, usaremos la probabilidad CRUDA como score 0-100.\n",
"# El umbral de decision lo manejara el Ensemble segun los tiers de amount.\n",
"# Esto nos da mas flexibilidad que un unico umbral binario.\n",
])

